def is_test(rel):
    p = rel.lower()
    b = os.path.basename(p)
    return bool(
        re.search(r"(^|/)(tests?|spec)(/|$)", p)
        or b.startswith("test_")
        or re.search(r"(_test|_spec|test)\.(\w+)$", b)
    )


def is_generated(text):
    head = text[:600]
    return bool(re.search(r"Generated by|@generated|DO NOT EDIT|auto-?generated", head, re.I))


# ---------------------------------------------------------------- lexers
# Each lexer returns: code_lines: set of line numbers (1-based) with code;
# comments: list of dict(line, end, text, doc, kind) where kind in line/block/docstring;
# a comment is "trailing" when its start line also has code before it.


def lex_cfamily(text, lang):
    comments = []
    code = set()
    trail_code_before = {}  # line -> bool code seen before first comment on that line
    i, n, line = 0, len(text), 1
    line_has_code = False

    def mark():
        code.add(line)

    while i < n:
        c = text[i]
        if c == "\n":
            line += 1
            line_has_code = False
            i += 1
            continue
        if c in " \t\r\f\v":
            i += 1
            continue
        two = text[i : i + 2]
        if two == "//":
            j = text.find("\n", i)
            j = n if j < 0 else j
            body = text[i:j]
            doc = body.startswith("///") and not body.startswith("////") or body.startswith("//!")
            comments.append(dict(line=line, end=line, text=body, doc=doc, kind="line", trailing=line_has_code))
            i = j
            continue
        if two == "/*":
            depth, j = 1, i + 2
            while j < n and depth:
                if text.startswith("*/", j):
                    depth -= 1
                    j += 2
                    continue
                if lang == "rust" and text.startswith("/*", j):
                    depth += 1
                    j += 2
                    continue
                j += 1
            body = text[i:j]
            doc = (body.startswith("/**") and not body.startswith("/**/") and not body.startswith("/***")) or body.startswith("/*!")
            end = line + body.count("\n")
            comments.append(dict(line=line, end=end, text=body, doc=doc, kind="block", trailing=line_has_code))
            line = end
            i = j
            continue
        # strings
        if lang == "rust" and (text.startswith('r"', i) or text.startswith("r#", i) or text.startswith('br"', i) or text.startswith("br#", i)):
            m = re.match(r'b?r(#*)"', text[i:])
            if m:
                close = '"' + m.group(1)
                j = text.find(close, i + m.end())
                j = n if j < 0 else j + len(close)
                mark()
                line_has_code = True
                line += text[i:j].count("\n")
                i = j
                continue
        if lang == "cpp" and text.startswith('R"', i):
            m = re.match(r'R"([^(\s]*)\(', text[i:])
            if m:
                close = ")" + m.group(1) + '"'
                j = text.find(close, i + m.end())
                j = n if j < 0 else j + len(close)
                mark()
                line_has_code = True
                line += text[i:j].count("\n")
                i = j
                continue
        if lang == "java" and text.startswith('"""', i):
            j = text.find('"""', i + 3)
            j = n if j < 0 else j + 3
            mark()
            line_has_code = True
            line += text[i:j].count("\n")
            i = j
            continue
        if c == '"':
            j = i + 1
            while j < n and text[j] != '"':
                if text[j] == "\\":
                    j += 1
                elif text[j] == "\n" and lang != "rust":
                    break
                j += 1
            j += 1
            mark()
            line_has_code = True
            line += text[i:j].count("\n")
            i = j
            continue
        if c == "'":
            m = re.match(r"'(\\(x[0-9a-fA-F]{2}|u\{[0-9a-fA-F]+\}|.)|[^\\'\n])'", text[i:])
            mark()
            line_has_code = True
            if m:
                i += m.end()
            else:
                i += 1  # lifetime or digit separator
            continue
        mark()
        line_has_code = True
        i += 1
    return code, comments


def lex_python(text):
    comments, code = [], set()
    doc_ranges = []
    try:
        tree = ast.parse(text)
        for node in ast.walk(tree):
            if isinstance(node, (ast.Module, ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)):
                body = getattr(node, "body", [])
                if body and isinstance(body[0], ast.Expr) and isinstance(getattr(body[0], "value", None), ast.Constant) and isinstance(body[0].value.value, str):
                    e = body[0]
                    doc_ranges.append((e.lineno, e.end_lineno, node))
    except SyntaxError:
        pass
    doc_lines = set()
    for s, e, node in doc_ranges:
        doc_lines.update(range(s, e + 1))
        lines = text.splitlines()
        comments.append(dict(line=s, end=e, text="\n".join(lines[s - 1 : e]), doc=True, kind="docstring", trailing=False,
                             owner=("module" if isinstance(node, ast.Module) else "def")))
    try:
        toks = list(tokenize.generate_tokens(io.StringIO(text).readline))
    except (tokenize.TokenError, IndentationError):
        toks = []
    for t in toks:
        if t.type == tokenize.COMMENT:
            ln = t.start[0]
            comments.append(dict(line=ln, end=ln, text=t.string, doc=False, kind="line", trailing=t.start[1] > 0 and t.line[: t.start[1]].strip() != ""))
        elif t.type in (tokenize.NL, tokenize.NEWLINE, tokenize.INDENT, tokenize.DEDENT, tokenize.ENDMARKER, tokenize.ENCODING):
            continue
        else:
            for ln in range(t.start[0], t.end[0] + 1):
                if ln not in doc_lines:
                    code.add(ln)
    return code, comments


def lex_ruby(text):
    comments, code = [], set()
    lines = text.split("\n")
    in_begin = None
    for idx, raw in enumerate(lines, 1):
        if in_begin is not None:
            if raw.startswith("=end"):
                comments.append(dict(line=in_begin, end=idx, text="\n".join(lines[in_begin - 1 : idx]), doc=False, kind="block", trailing=False))
                in_begin = None
            continue
        if raw.startswith("=begin"):
            in_begin = idx
            continue
        # scan for # outside strings
        i, q, has = 0, None, False
        while i < len(raw):
            ch = raw[i]
            if q:
                if ch == "\\":
                    i += 2
                    continue
                if ch == q:
                    q = None
                i += 1
                continue
            if ch in "\"'`":
                q = ch
                has = True
            elif ch == "#" and not (i > 0 and raw[i - 1] == "?"):
                comments.append(dict(line=idx, end=idx, text=raw[i:], doc=False, kind="line", trailing=has))
                break
            elif not ch.isspace():
                has = True
            i += 1
        if has:
            code.add(idx)
    return code, comments


def cobol_is_free(text, path, repo_free):
    if re.search(r">>\s*SOURCE\s+(FORMAT\s+)?(IS\s+)?FREE", text[:2000], re.I):
        return True
    if re.search(r">>\s*SOURCE\s+(FORMAT\s+)?(IS\s+)?FIXED", text[:2000], re.I):
        return False
    if repo_free:
        return True
    lines = [l for l in text.split("\n") if l.strip()]
    if not lines:
        return repo_free
    # fixed: content starts at col >= 8 (or indicator col 7); free: something starting in cols 1-6
    early = sum(1 for l in lines if (len(l) - len(l.lstrip(" "))) < 6 and not l.lstrip().startswith("*>"))
    return early / len(lines) > 0.2 or repo_free and early > 0


def lex_cobol(text, free):
    comments, code = [], set()
    for idx, raw in enumerate(text.split("\n"), 1):
        line = raw.rstrip("\r")
        if not free:
            if len(line) >= 7 and line[6] in "*/":
                comments.append(dict(line=idx, end=idx, text=line[6:], doc=False, kind="line", trailing=False))
                continue
            area = line[7:] if len(line) > 7 else ""
            pre = line[6:7] if len(line) > 6 else ""
            if pre not in (" ", "-", "D", "d", ""):
                area = line[6:]
            # handle free-style *> starting before col 7 too
            if line[:6].lstrip().startswith("*>"):
                comments.append(dict(line=idx, end=idx, text=line.lstrip(), doc=False, kind="line", trailing=False))
                continue
            seg = area
        else:
            seg = line
        # find *> outside quotes
        i, q, has = 0, None, False
        while i < len(seg):
            ch = seg[i]
            if q:
                if ch == q:
                    q = None
                i += 1
                continue
            if ch in "\"'":
                q = ch
                has = True
            elif seg.startswith("*>", i):
                comments.append(dict(line=idx, end=idx, text=seg[i:], doc=False, kind="line", trailing=has))
                break
            elif not ch.isspace():
                has = True
            i += 1
        if has:
            code.add(idx)
    return code, comments


# ---------------------------------------------------------------- definitions
C_KW = {"if", "for", "while", "switch", "return", "sizeof", "else", "do", "case", "catch", "new", "delete", "throw", "defined", "assert", "static_assert", "decltype", "alignof", "typeof"}
C_DEF = re.compile(r"^\s*(?:template\s*<[^>]*>\s*)?[A-Za-z_][\w:<>,\*&\s~\[\]]*?\b(~?[A-Za-z_]\w*(?:::~?[A-Za-z_]\w*)*|operator\s*\S+)\s*\(([^;{}]*)\)?\s*(?:const)?\s*(?:noexcept)?\s*(?:override|final)?\s*(?:->\s*[\w:<>\*& ]+)?\s*(?::[^;{]*)?\{?\s*$")
JAVA_DEF = re.compile(r"^\s*(?:@\w+\s+)*(?:(?:public|private|protected|static|final|abstract|synchronized|native|default)\s+)*(?:<[^>]+>\s+)?[\w<>\[\],.? ]+\s+(\w+)\s*\([^;]*\)?\s*(?:throws [\w., ]+)?\s*\{?\s*$")
JAVA_CLASS = re.compile(r"^\s*(?:(?:public|private|protected|static|final|abstract|sealed)\s+)*(?:class|interface|enum|record)\s+\w+")
RUST_DEF = re.compile(r"^\s*(?:pub(?:\([^)]*\))?\s+)?(?:const\s+)?(?:async\s+)?(?:unsafe\s+)?(?:extern\s+\"\w+\"\s+)?fn\s+\w+")
RUST_TYPE = re.compile(r"^\s*(?:pub(?:\([^)]*\))?\s+)?(?:struct|enum|trait|impl|mod|type|union)\b")
PY_DEF = re.compile(r"^\s*(?:async\s+)?(?:def|class)\s+\w+")
RB_DEF = re.compile(r"^\s*(?:def|class|module)\s+\S+")
COB_RESERVED = {"EXIT", "GOBACK", "CONTINUE", "END-IF", "END-PERFORM", "END-EVALUATE", "END-READ", "END-CALL", "END-COMPUTE", "END-STRING", "END-SEARCH", "END-WRITE", "END-RETURN", "END-UNSTRING", "END-ADD", "END-SUBTRACT", "END-MULTIPLY", "END-DIVIDE", "END-ACCEPT", "END-DISPLAY", "END-START", "END-REWRITE", "END-DELETE", "ELSE", "STOP", "RUN", "REPOSITORY", "PROGRAM", "END-EXEC", "THEN", "OTHER", "TRUE", "FALSE", "ZERO", "ZEROS", "ZEROES", "SPACE", "SPACES"}
COB_NONPROC_SECTIONS = {"WORKING-STORAGE", "LOCAL-STORAGE", "LINKAGE", "FILE", "CONFIGURATION", "INPUT-OUTPUT", "SCREEN", "REPORT", "COMMUNICATION"}
COB_PARA = re.compile(r"^\s*([A-Za-z0-9][A-Za-z0-9_-]*)(\s+SECTION)?\s*\.\s*(\*>.*)?$", re.I)


def strip_comments_line(lines_text, comments):
    """Return per-line code text with comments blanked (for def/brace detection)."""
    out = list(lines_text)
    for c in comments:
        if c["kind"] == "docstring":
            for ln in range(c["line"], c["end"] + 1):
                out[ln - 1] = ""
            continue
        if c["line"] == c["end"]:
            s = out[c["line"] - 1]
            k = s.find(c["text"].split("\n")[0])
            if k >= 0:
                out[c["line"] - 1] = s[:k]
        else:
            first = c["text"].split("\n")[0]
            s = out[c["line"] - 1]
            k = s.find(first)
            out[c["line"] - 1] = s[:k] if k >= 0 else s
            for ln in range(c["line"] + 1, c["end"]):
                out[ln - 1] = ""
            last = c["text"].split("\n")[-1]
            s = out[c["end"] - 1]
            k = s.find(last)
            out[c["end"] - 1] = s[k + len(last):] if k >= 0 else s
    return out


def find_defs(lang, code_text, code_lines, ext, free):
    """Return list of (line, kind, name, end_line). kind = func|type|para."""
    defs = []
    nlines = len(code_text)
    if lang in ("c", "cpp", "java", "rust"):
        for i, s in enumerate(code_text, 1):
            if i not in code_lines:
                continue
            st = s.strip()
            kind = None
            name = None
            if lang == "rust":
                if RUST_DEF.match(s):
                    kind, name = "func", re.search(r"fn\s+(\w+)", s).group(1)
                elif RUST_TYPE.match(s):
                    kind, name = "type", st.split()[1] if len(st.split()) > 1 else "?"
            elif lang == "java":
                if JAVA_CLASS.match(s):
                    kind, name = "type", "class"
                else:
                    m = JAVA_DEF.match(s)
                    if m and m.group(1) not in C_KW and not re.match(r"^\s*(return|new|else|throw)\b", s) and "=" not in s.split("(")[0]:
                        kind, name = "func", m.group(1)
            else:
                if st.startswith("#") or st.endswith(";") or st.endswith(","):
                    continue
                m = C_DEF.match(s)
                if m:
                    nm = m.group(1).split("::")[-1]
                    head = s.split("(")[0]
                    if nm in C_KW or "=" in head or re.match(r"^\s*(return|else|case|delete|new|throw|goto)\b", s):
                        m = None
                    elif len(head.split()) < 2 and "::" not in head and not re.match(r"^\s*~?[A-Z]\w*\s*\(", s):
                        # plain call like foo(x) {  -- require a return type except constructors
                        m = None
                if m:
                    # confirm a body follows: '{' on this line or the next code line
                    nxt = s.rstrip().endswith("{")
                    if not nxt:
                        for j in range(i, min(i + 4, nlines)):
                            t = code_text[j].strip()
                            if not t:
                                continue
                            if t.startswith("{") or t.startswith(":"):
                                nxt = True
                            elif t.endswith(")") or t.endswith(") const") or t.endswith("{"):
                                nxt = t.endswith("{") or None
                                if nxt:
                                    break
                                continue
                            break
                    if nxt:
                        kind, name = "func", m.group(1)
                elif re.match(r"^\s*(typedef\s+)?(struct|class|enum|union)\s+\w*\s*(:[^;{]*)?\{?\s*$", s) and not st.endswith(";"):
                    kind, name = "type", "type"
            if kind:
                defs.append([i, kind, name, None])
        # end lines by brace matching
        for d in defs:
            depth, started, end = 0, False, None
            for j in range(d[0], min(nlines, d[0] + 5000) + 1):
                s = code_text[j - 1]
                s = re.sub(r'"(\\.|[^"\\])*"', '""', s)
                s = re.sub(r"'(\\.|[^'\\])'", "''", s)
                for ch in s:
                    if ch == "{":
                        depth += 1
                        started = True
                    elif ch == "}":
                        depth -= 1
                if started and depth <= 0:
                    end = j
                    break
                if not started and j > d[0] + 4:
                    break
            d[3] = end or d[0]
    elif lang == "python":
        for i, s in enumerate(code_text, 1):
            if PY_DEF.match(s):
                ind = len(s) - len(s.lstrip())
                end = i
                for j in range(i + 1, nlines + 1):
                    t = code_text[j - 1]
                    if t.strip() == "":
                        continue
                    if len(t) - len(t.lstrip()) <= ind and j in code_lines:
                        break
                    end = j
                defs.append([i, "type" if s.lstrip().startswith("class") else "func", s.split()[1].split("(")[0], end])
    elif lang == "ruby":
        for i, s in enumerate(code_text, 1):
            if RB_DEF.match(s):
                ind = len(s) - len(s.lstrip())
                end = i
                for j in range(i + 1, nlines + 1):
                    t = code_text[j - 1]
                    if t.strip() == "":
                        continue
                    if len(t) - len(t.lstrip()) <= ind:
                        end = j
                        break
                    end = j
                defs.append([i, "func" if s.lstrip().startswith("def") else "type", s.split()[1], end])
    elif lang == "cobol":
        in_proc = ext == ".cpy"
        datalike = 0
        verbs = 0
        for s in code_text:
            u = s.upper()
            if re.search(r"\bPIC(TURE)?\b|^\s*\d\d\s+\S", u):
                datalike += 1
            if re.search(r"^\s*(MOVE|PERFORM|DISPLAY|COMPUTE|IF|EVALUATE|CALL|ADD|SET)\b", u):
                verbs += 1
        if ext == ".cpy" and verbs < datalike / 3:
            in_proc = False
        for i, s in enumerate(code_text, 1):
            u = s.upper()
            if re.search(r"\bPROCEDURE\s+DIVISION\b", u):
                in_proc = True
                continue
            if re.search(r"\b(DATA|ENVIRONMENT|IDENTIFICATION)\s+DIVISION\b", u):
                in_proc = False
                continue
            if i not in code_lines:
                continue
            m = COB_PARA.match(s.split("*>")[0] + ("" if "*>" not in s else "") )
            if not m:
                continue
            name = m.group(1).upper()
            if name in COB_RESERVED or name.isdigit():
                continue
            is_sec = bool(m.group(2))
            if is_sec and name in COB_NONPROC_SECTIONS:
                continue
            if not in_proc:
                continue
            # fixed format: paragraph names start in area A (col 8-11)
            if not free:
                lead = len(s) - len(s.lstrip(" "))
                if lead > 10:
                    continue
            else:
                lead = len(s) - len(s.lstrip(" "))
                # free format: names usually at low indentation; reject deep ones
                if lead > 8:
                    continue
            defs.append([i, "section" if is_sec else "para", name, None])
        for k, d in enumerate(defs):
            d[3] = (defs[k + 1][0] - 1) if k + 1 < len(defs) else nlines
    return defs


