def process_file(pair, lang, agent, repo, role, path, rel, repo_free=False):
    raw = open(path, "rb").read()
    text = raw.decode("utf-8", errors="replace")
    if is_generated(text):
        return None
    text = text.replace("\r\n", "\n")
    ext = os.path.splitext(path)[1].lower()
    free = False
    if lang in ("c", "cpp", "java", "rust"):
        code, comments = lex_cfamily(text, lang)
    elif lang == "python":
        code, comments = lex_python(text)
    elif lang == "ruby":
        code, comments = lex_ruby(text)
    else:
        free = cobol_is_free(text, path, repo_free)
        code, comments = lex_cobol(text, free)
    lines_text = text.split("\n")
    code_text = strip_comments_line(lines_text, comments) if lang != "cobol" else [
        (l[7:72] if (not free and len(l) > 7 and l[6:7] not in "*/") else ("" if not free else l)) for l in lines_text
    ]
    if lang == "cobol" and not free:
        # keep area A from column 8 with 7 leading spaces so indentation tests work
        code_text = ["       " + t if t else "" for t in code_text]
    # comment-only lines in COBOL code_text should be blank
    for c in comments:
        if lang == "cobol" and not c["trailing"]:
            code_text[c["line"] - 1] = ""
    defs = find_defs(lang, code_text, code, ext, free)
    proc_lines = set()
    if lang == "cobol":
        inp = ext == ".cpy" and any(d[1] in ("para", "section") for d in defs)
        for i, s in enumerate(code_text, 1):
            u = s.upper()
            if re.search(r"\bPROCEDURE\s+DIVISION\b", u):
                inp = True
            elif re.search(r"\b(DATA|ENVIRONMENT|IDENTIFICATION)\s+DIVISION\b", u):
                inp = False
            if inp:
                proc_lines.add(i)
    first_code = min(code) if code else 10 ** 9

    # ---- merge into blocks
    comments.sort(key=lambda c: (c["line"], c["end"]))
    blocks = []
    for c in comments:
        if c["trailing"] or c["kind"] == "docstring":
            blocks.append(dict(start=c["line"], end=c["end"], parts=[c], trailing=c["trailing"]))
            continue
        if blocks and not blocks[-1]["trailing"] and blocks[-1]["parts"][-1]["kind"] != "docstring" and c["line"] == blocks[-1]["end"] + 1 and not any(ln in code for ln in range(c["line"], c["end"] + 1) if False):
            blocks[-1]["parts"].append(c)
            blocks[-1]["end"] = c["end"]
        else:
            blocks.append(dict(start=c["line"], end=c["end"], parts=[c], trailing=False))

    def_lines = {d[0]: d for d in defs}
    def_starts = sorted(def_lines)
    rows = []
    for b in blocks:
        txt = "\n".join(p["text"] for p in b["parts"])
        body = strip_markers(txt, lang)
        words = len(re.findall(r"[A-Za-z0-9][A-Za-z0-9'_-]*", body))
        doc = any(p["doc"] for p in b["parts"])
        nl = b["end"] - b["start"] + 1
        # position
        pos = "other"
        target = None
        if b["trailing"]:
            pos = "trailing"
        elif b["parts"][0]["kind"] == "docstring":
            pos = "header" if b["parts"][0].get("owner") == "module" else "preceding_def"
            if pos == "preceding_def":
                cands = [d for d in def_starts if d < b["start"]]
                target = cands[-1] if cands else None
        else:
            # preceding a def: skip blank/attribute lines below the block, def within 2 lines
            j = b["end"] + 1
            gap = 0
            while j <= len(lines_text):
                if j in def_lines:
                    break
                t = code_text[j - 1] if j - 1 < len(code_text) else ""
                if ATTR.match(t) or (lang == "python" and t.strip().startswith("@")):
                    j += 1
                    continue
                if t.strip() == "" and j not in code:
                    gap += 1
                    if gap > 1:
                        break
                    j += 1
                    continue
                break
            if b["end"] < first_code:
                pos = "header"
                if j in def_lines:
                    target = j  # a file-top comment directly above the first definition also documents it
            elif j in def_lines:
                pos = "preceding_def"
                target = j
            else:
                inside = any(d[0] < b["start"] <= (d[3] or d[0]) and d[1] in ("func", "para", "section") for d in defs)
                if lang == "cobol" and b["start"] in proc_lines:
                    inside = True
                pos = "inside_body" if inside else "other"
        rows.append(dict(pair=pair, lang=lang, agent=agent, role=role, repo=os.path.basename(repo), file=rel,
                         test=int(is_test(rel)), line=b["start"], lines=nl, words=words, position=pos,
                         doc_form=int(doc), kind=b["parts"][0]["kind"], target_def=target or "", _text=txt))
    targeted = {r["target_def"] for r in rows if r["target_def"]}
    drows = [dict(pair=pair, agent=agent, role=role, repo=os.path.basename(repo), file=rel, test=int(is_test(rel)), line=d[0], kind=d[1], name=d[2],
                  length=(d[3] or d[0]) - d[0] + 1, commented=int(d[0] in targeted)) for d in defs]
    frow = dict(pair=pair, lang=lang, agent=agent, role=role, repo=os.path.basename(repo), file=rel, test=int(is_test(rel)),
                code_lines=len(code), comment_lines=len({ln for c in comments for ln in range(c["line"], c["end"] + 1)}),
                comment_only_lines=len({ln for c in comments for ln in range(c["line"], c["end"] + 1)} - code),
                defs=len(defs), cobol_free=int(free))
    code_only = "\n".join((t.split("*>")[0] if lang == "cobol" else t) for t in code_text)
    return frow, rows, drows, code_only


def strip_markers(txt, lang):
    out = []
    for l in txt.split("\n"):
        s = l.strip()
        s = re.sub(r'^(///?|//!|/\*\*?|\*/|\*>|\*|#+|"""|\'\'\'|/)', "", s)
        s = re.sub(r"(\*/|\"\"\"|''')\s*$", "", s)
        out.append(s.strip())
    return "\n".join(out)


def main():
    files, blocks, defs = [], [], []
    code_dump = {}
    for pair, lang, agent, repo, role in REPOS:
        exts = EXT[lang]
        repo_free = False
        if lang == "cobol":
            # repo-level free default: main program declares FREE
            for dp, dn, fn in os.walk(repo):
                dn[:] = [x for x in dn if not x.startswith(".") and x not in SKIP_DIRS]
                for f in fn:
                    if f.lower().endswith((".cob", ".cbl")):
                        t = open(os.path.join(dp, f), errors="replace").read(3000)
                        if re.search(r">>\s*SOURCE\s+(FORMAT\s+)?(IS\s+)?FREE", t, re.I):
                            repo_free = True
                    # build files: cobc -free / -F / -fformat=free means every source is free format
                    if f == "Makefile" or f.endswith((".sh", ".mk")):
                        t = open(os.path.join(dp, f), errors="replace").read()
                        if re.search(r"(^|[\s\"'])(-free|-F|-fformat=free)([\s\"']|$)", t):
                            repo_free = True
            print("cobol", os.path.basename(repo), "free" if repo_free else "fixed/auto", file=sys.stderr)
        for dp, dn, fn in os.walk(repo):
            dn[:] = sorted(x for x in dn if not x.startswith(".") and x not in SKIP_DIRS)
            for f in sorted(fn):
                if os.path.splitext(f)[1].lower() not in exts:
                    continue
                p = os.path.join(dp, f)
                rel = os.path.relpath(p, repo)
                r = process_file(pair, lang, agent, repo, role, p, rel, repo_free)
                if r is None:
                    print("skip generated", rel, file=sys.stderr)
                    continue
                files.append(r[0])
                code_dump.setdefault(os.path.basename(repo), []).append(r[3])
                blocks.extend(r[1])
                defs.extend(r[2])
    os.makedirs(CODE_DIR, exist_ok=True)
    for repo_name, parts in code_dump.items():
        open(os.path.join(CODE_DIR, repo_name + ".txt"), "w").write("\n".join(parts))
    for i, b in enumerate(blocks):
        b["block_id"] = i
    with open(TEXT_CACHE, "w") as fh:
        for b in blocks:
            fh.write(json.dumps({"block_id": b["block_id"], "lang": b["lang"], "text": b["_text"]}) + "\n")

    def w(name, rows, cols):
        with open(os.path.join(OUT, name), "w", newline="") as fh:
            wr = csv.DictWriter(fh, fieldnames=cols, extrasaction="ignore")
            wr.writeheader()
            wr.writerows(rows)

    w("files.csv", files, list(files[0].keys()))
    w("blocks.csv", blocks, ["block_id"] + [k for k in blocks[0] if k != "_text" and k != "block_id"])
    w("defs.csv", defs, list(defs[0].keys()))
    print(len(files), "files", len(blocks), "blocks", len(defs), "defs")


if __name__ == "__main__":
    main()
